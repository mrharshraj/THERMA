// Active Alerts — rules-engine alerts (active_alerts_2).

import { getState } from '../app/store.js';
import { el, icon, pageHeader, card, statTile, emptyState, btnGhost, severityChip, timeAgo, toast } from '../app/widgets.js';
import { placePicker, modeBadgeFor } from '../app/placepick.js';
import { navigate } from '../app/router.js';
import { donut } from '../app/charts.js';

let filter = 'all';

export default {
  title: 'Active Alerts',
  async render(container) {
    const st = getState();
    const ctx = st.context;
    const alerts = ctx ? ctx.alerts || [] : [];
    const highlightId = (st._routeQuery && st._routeQuery.highlight) || null;

    container.appendChild(pageHeader({
      eyebrow: 'RULES ENGINE',
      title: 'Active Alerts',
      subtitle: ctx ? `${alerts.length} alert${alerts.length === 1 ? '' : 's'} generated for <b>${ctx.location.display}</b> by THERMA threshold rules over the current heat layer.` : 'Threshold breaches generated by THERMA rules.',
      badge: ctx ? modeBadgeFor(ctx) : null,
      actions: [placePicker()],
    }));

    if (!ctx) {
      container.appendChild(emptyState({ ic: 'notifications_off', title: 'No context loaded', message: 'Load heat data to generate alerts.' }));
      return;
    }

    // KPI row
    const crit = alerts.filter((a) => a.severity === 'Critical').length;
    const high = alerts.filter((a) => a.severity === 'High').length;
    container.appendChild(el('div', { class: 'grid gap-xs mb-md', style: { gridTemplateColumns: 'repeat(auto-fit,minmax(150px,1fr))' } },
      statTile({ label: 'Total Active', value: String(alerts.length), sub: 'this analysis cycle', ic: 'notification_important' }),
      statTile({ label: 'Critical', value: String(crit), sub: crit ? 'immediate attention' : 'none', ic: 'error' }),
      statTile({ label: 'High', value: String(high), sub: high ? 'schedule mitigation' : 'none', ic: 'warning' }),
      statTile({ label: 'Latest', value: alerts[0] ? timeAgo(alerts[0].time) : '—', sub: alerts[0] ? alerts[0].type : '', ic: 'schedule' })));

    const grid = el('div', { class: 'grid gap-md flex-1 min-h-0 grid-cols-1 lg:grid-cols-[minmax(0,1.5fr)_minmax(280px,0.8fr)]' });

    // ---------- left: filters + list ----------
    const left = el('div', { class: 'flex flex-col gap-md min-w-0 overflow-y-auto pr-1' });

    const filters = el('div', { class: 'flex gap-1.5 flex-wrap', dataset: { alertFilters: '' } },
      ['all', 'Critical', 'High'].map((f) => filterChip(f)));
    left.appendChild(filters);

    const listHost = el('div', { class: 'flex flex-col gap-2.5', dataset: { alertList: '' } });
    left.appendChild(listHost);
    renderList(listHost, alerts, highlightId);

    // ---------- right ----------
    const right = el('div', { class: 'flex flex-col gap-md min-w-0 min-h-0 lg:overflow-y-auto pr-1' });

    if (alerts.length) {
      const bySev = {};
      alerts.forEach((a) => { bySev[a.severity] = (bySev[a.severity] || 0) + 1; });
      const colors = { Critical: '#b91c1c', High: '#f97316', Medium: '#eab308', Low: '#2b7de9' };
      right.appendChild(card({
        title: 'Severity Mix', ic: 'donut_small',
        children: donut({
          segments: Object.entries(bySev).map(([label, value]) => ({ label, value, color: colors[label] || '#747878' })),
          centerLabel: String(alerts.length), centerSub: 'alerts',
        }),
      }));
    }

    right.appendChild(card({
      title: 'How alerts are produced', ic: 'rule',
      children: el('div', { class: 'text-[12px] text-on-surface-variant/90 flex flex-col gap-2' },
        el('p', {}, 'THERMA evaluates rules against the loaded FortyGuard layer and environmental parameters:'),
        ruleRow('Exposure score ≥ 75 → Critical heat alert'),
        ruleRow('Asset in High/Critical band → asset-level alert'),
        ruleRow('Heat index > 36°C → advisory')),
    }));

    grid.appendChild(left);
    grid.appendChild(right);
    container.appendChild(grid);

    function filterChip(f) {
      const active = filter === f;
      return el('button', {
        class: `squishy-btn rounded-full px-3.5 py-1.5 text-[11px] font-bold ${active ? 'bg-primary text-on-primary dark:bg-inverse-primary dark:text-inverse-on-surface' : 'glass-chip'}`,
        onclick: () => { filter = f; rerenderFilters(); renderList(listHost, alerts, null); },
      }, f === 'all' ? `All (${alerts.length})` : f);
    }
    function rerenderFilters() {
      const host = document.querySelector('[data-alert-filters]');
      if (!host) return;
      host.innerHTML = '';
      ['all', 'Critical', 'High'].forEach((f) => host.appendChild(filterChip(f)));
    }
  },
};

function ruleRow(text) {
  return el('div', { class: 'flex items-center gap-2 glass-chip rounded-lg px-2.5 py-1.5 text-[11px]' },
    icon('check_circle', 'text-[13px] text-green-600'), text);
}

function renderList(host, alerts, highlightId) {
  host.innerHTML = '';
  let shown = alerts;
  if (filter !== 'all') shown = alerts.filter((a) => a.severity === filter);
  if (!shown.length) {
    host.appendChild(emptyState({ ic: 'verified', title: 'No alerts match', message: 'The rules engine found nothing matching this filter.' }));
    return;
  }
  shown.forEach((a) => host.appendChild(alertCard(a)));
  if (highlightId) {
    requestAnimationFrame(() => {
      const target = host.querySelector(`[data-alert-id="${highlightId}"]`);
      if (target) {
        target.scrollIntoView({ behavior: 'smooth', block: 'center' });
        target.classList.add('ring-2', 'ring-orange-500/80');
        setTimeout(() => target.classList.remove('ring-2', 'ring-orange-500/80'), 4000);
      }
    });
  }
}

function alertCard(a) {
  return el('div', {
    class: 'glass-panel rounded-2xl p-md hover-lift fade-up',
    dataset: { alertId: a.id },
    role: 'article',
    'aria-label': `${a.severity} ${a.type} alert`,
  },
  el('div', { class: 'flex items-start justify-between gap-sm mb-1.5 flex-wrap' },
    el('span', { class: 'flex items-center gap-2 flex-wrap' }, severityChip(a.severity),
      el('span', { class: 'text-[13px] font-black' }, a.type)),
    el('span', { class: 'text-[10.5px] font-semibold text-on-surface-variant/70' }, `${timeAgo(a.time)} · ${a.location}`)),
  el('p', { class: 'text-[12.5px] leading-snug mb-1.5' }, a.description),
  el('div', { class: 'grid gap-xs mb-sm', style: { gridTemplateColumns: 'repeat(auto-fit,minmax(200px,1fr))' } },
    infoBlock('crisis_alert', 'Impact', a.impact),
    infoBlock('tips_and_updates', 'Recommended action', a.recommendation)),
  el('div', { class: 'flex items-center gap-xs flex-wrap pt-1 border-t border-outline-variant/20 dark:border-outline/10' },
    a.assetId
      ? btnGhost('Open Asset', 'domain', () => navigate('location', { param: `asset:${a.assetId}` }))
      : btnGhost('View on Heat Map', 'local_fire_department', () => navigate('heat')),
    btnGhost('Ask Zoe', 'smart_toy', () => window.dispatchEvent(new CustomEvent('therma:zoe-send', { detail: `What should we do about the ${a.type} at ${a.location}?` }))),
    el('button', {
      class: 'ml-auto p-1.5 rounded-full hover:bg-surface-container text-on-surface-variant',
      title: 'Copy alert summary',
      onclick: async () => {
        try {
          await navigator.clipboard.writeText(`[THERMA ${a.severity}] ${a.type} — ${a.location}: ${a.description}`);
          toast('Alert copied.', 'success');
        } catch { toast('Clipboard unavailable.', 'warn'); }
      },
    }, icon('content_copy', 'text-[15px]', false))));
}

function infoBlock(icName, label, text) {
  return el('div', { class: 'glass-chip rounded-xl p-2.5' },
    el('div', { class: 'flex items-center gap-1.5 mb-1' }, icon(icName, 'text-[14px] text-on-surface-variant'),
      el('span', { class: 'text-[9.5px] font-bold uppercase tracking-wider text-on-surface-variant/70' }, label)),
    el('p', { class: 'text-[11.5px] leading-snug' }, text));
}
